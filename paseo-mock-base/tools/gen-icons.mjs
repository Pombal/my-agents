#!/usr/bin/env -S node --no-warnings
// Generates kit/icons.js: every Lucide icon (the set Paseo uses), at the exact
// version Paseo pins, as SVG inner markup. Mocks write <i data-icon="plus"></i>.
//
//   node tools/gen-icons.mjs [path/to/paseo-checkout]
//
// Rerun after a Paseo update. Custom (non-Lucide) icons live in kit/icons-extra.js.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { homedir } from "node:os";

const here = dirname(fileURLToPath(import.meta.url));
const configPath = join(homedir(), ".config/my-agents/paseo.json");
const config = existsSync(configPath) ? JSON.parse(readFileSync(configPath, "utf8")) : {};
const root = resolve(process.argv[2] ?? process.env.PASEO_SOURCE_CHECKOUT ?? config.sourceCheckout ?? `${homedir()}/forkspace/paseo-wt/fork`);
const pkgDir = join(root, "node_modules/lucide-react");
const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;
const iconDir = join(pkgDir, "dist/esm/icons");

const esc = (v) => String(v).replace(/&/g, "&amp;").replace(/"/g, "&quot;");
const icons = {};
for (const file of readdirSync(iconDir).filter((f) => f.endsWith(".js")).sort()) {
  const { __iconNode } = await import(pathToFileURL(join(iconDir, file)).href);
  if (!__iconNode) continue;
  icons[file.slice(0, -3)] = __iconNode
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${esc(v)}"`).join(" ");
      return `<${tag} ${a}/>`;
    })
    .join("");
}

const out = resolve(here, "../kit/icons.js");
writeFileSync(
  out,
  `/* GENERATED by tools/gen-icons.mjs from lucide-react ${version} (Paseo's pinned version). Do not edit. */\n` +
    `window.KitIcons = Object.assign(window.KitIcons || {}, ${JSON.stringify(icons)});\n`,
);
console.log(`wrote ${out}: ${Object.keys(icons).length} icons, lucide ${version}`);
