#!/usr/bin/env -S node --no-warnings
// Generates kit/tokens.css from Paseo's own theme file, so the mock's colours,
// font sizes, spacing and radii always match the real app.
//
//   node tools/gen-tokens.mjs [path/to/theme.ts]
//
// Default source: the fork worktree that `paseo-fork-sync` keeps current.
// Rerun after every Paseo update. Never hand-edit kit/tokens.css.

import { register } from "node:module";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { homedir } from "node:os";

const here = dirname(fileURLToPath(import.meta.url));
const configPath = join(homedir(), ".config/my-agents/paseo.json");
const config = existsSync(configPath) ? JSON.parse(readFileSync(configPath, "utf8")) : {};
const sourceCheckout = process.env.PASEO_SOURCE_CHECKOUT ?? config.sourceCheckout ?? `${homedir()}/forkspace/paseo-wt/fork`;
const themePath = resolve(
  process.argv[2] ??
    join(sourceCheckout, "packages/app/src/styles/theme.ts"),
);

// theme.ts imports react-native (only Platform.select, for font stacks) and
// @getpaseo/highlight (syntax colours). Stub react-native to pick the web value;
// let highlight resolve for real, falling back to empty colour maps.
const stubs = {
  "react-native": `export const Platform = { OS: "web", select: (o) => ("web" in o ? o.web : o.default) };`,
  "@getpaseo/highlight-fallback": `export const darkHighlightColors = {}; export const lightHighlightColors = {};`,
};
const hooks = `
const stubs = ${JSON.stringify(stubs)};
export async function resolve(spec, ctx, next) {
  if (spec in stubs) return { url: "stub:" + spec, shortCircuit: true };
  try { return await next(spec, ctx); }
  catch (e) {
    if (spec === "@getpaseo/highlight") return { url: "stub:@getpaseo/highlight-fallback", shortCircuit: true };
    throw e;
  }
}
export async function load(url, ctx, next) {
  if (url.startsWith("stub:")) return { format: "module", source: stubs[url.slice(5)], shortCircuit: true };
  return next(url, ctx);
}`;
register(`data:text/javascript,${encodeURIComponent(hooks)}`, import.meta.url);

const t = await import(pathToFileURL(themePath).href);

// CSS name for each Paseo theme preference (data-theme value) -> theme object.
const themes = Object.fromEntries(
  t.THEME_OPTIONS.filter((o) => o.theme).map((o) => [o.name, o.theme]),
);

const kebab = (s) => String(s).replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/\./g, "_").toLowerCase();
const px = (v) => (typeof v === "number" ? `${v}px` : v);

function flatten(obj, prefix, out) {
  for (const [k, v] of Object.entries(obj)) {
    const name = `${prefix}-${kebab(k)}`;
    if (v && typeof v === "object") flatten(v, name, out);
    else out.push(`  ${name}: ${v};`);
  }
  return out;
}

function themeBlock(theme) {
  const { palette, ...colors } = theme.colors;
  const lines = flatten(colors, "--c", []);
  lines.push(`  color-scheme: ${theme.colorScheme};`);
  for (const [k, s] of Object.entries(theme.shadow)) {
    lines.push(`  --shadow-${k}: 0 ${s.shadowOffset.height}px ${s.shadowRadius}px ${s.shadowColor};`);
  }
  return lines.join("\n");
}

const common = t.darkTheme;
const scale = (name, obj, unit = px) =>
  Object.entries(obj).map(([k, v]) => `  --${name}-${kebab(k)}: ${unit(v)};`);

const rootLines = [
  ...scale("sp", common.spacing),
  ...scale("fs", common.fontSize),
  // Paseo's applyAppearance() (appearance/apply.ts) overwrites the authored diff line-height
  // at startup with round(code × 1.5); chat text uses round(content × 1.4) (components/message.tsx).
  ...scale("lh", { ...common.lineHeight, diff: Math.round(common.fontSize.code * 1.5) }),
  `  --lh-content: ${Math.round(common.fontSize.content * 1.4)}px;`,
  ...scale("icon", common.iconSize),
  ...scale("fw", common.fontWeight, (v) => (v === "normal" ? 400 : v === "bold" ? 700 : v)),
  ...scale("r", common.borderRadius),
  `  --icon-stroke: ${t.ICON_STROKE_WIDTH};`,
  `  --font-ui: ${common.fontFamily.ui};`,
  `  --font-mono: ${common.fontFamily.mono};`,
  `  --content-max-width: ${common.contentMaxWidth}px;`,
];

const blocks = Object.entries(themes).map(
  ([name, theme]) => `[data-theme="${name}"] {\n${themeBlock(theme)}\n}`,
);

const css = `/* GENERATED by tools/gen-tokens.mjs from Paseo packages/app/src/styles/theme.ts
 * on ${new Date().toISOString().slice(0, 10)}. Do not edit; rerun the script.
 * Themes (data-theme values): ${Object.keys(themes).join(", ")}
 * Colour vars: --c-<token>, e.g. --c-surface1, --c-foreground-muted,
 * --c-status-success, --c-terminal-background, --c-syntax-keyword.
 */
:root {
${rootLines.join("\n")}
}

${blocks.join("\n\n")}
`;

const outPath = resolve(here, "../kit/tokens.css");
writeFileSync(outPath, css);
console.log(`wrote ${outPath} (${Object.keys(themes).length} themes)`);
